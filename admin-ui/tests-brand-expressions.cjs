const { chromium, expect } = require(process.cwd()+'/node_modules/@playwright/test')
;(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true})
 try {
 const page=await browser.newPage({viewport:{width:1440,height:950}})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 const base=process.env.BRAND_TEST_BASE || 'http://127.0.0.1:18132'
 await page.goto(base+'/admin/')
 await page.locator('input').first().fill('admin')
 await page.locator('input[type=password]').fill('Brand-fixture-12345')
 await page.getByRole('button',{name:'登录运营后台'}).click()
 await expect(page.getByRole('heading',{name:'品牌 IP 管理',exact:true})).toBeVisible()
 const name='本地验收 IP '+Date.now()
 await page.getByRole('button',{name:'新增 IP',exact:true}).click()
 let dialog=page.getByRole('dialog')
 await dialog.locator('.el-form-item').filter({hasText:'IP 名称'}).locator('input').fill(name)
 await dialog.locator('.el-form-item').filter({hasText:'所属城市'}).locator('input').fill('杭州')
 await page.getByRole('option',{name:'杭州',exact:true}).click()
 await dialog.getByRole('button',{name:'保存草稿',exact:true}).click()
 const ip=page.getByRole('row').filter({hasText:name})
 await ip.getByRole('button',{name:'表情管理',exact:true}).click()
 async function add(label){
  await page.getByRole('button',{name:'新增表情',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'新增表情'})
  await dialog.locator('.el-form-item').filter({hasText:'表情名称'}).locator('input').fill(label)
  await dialog.getByRole('button',{name:'上传图片',exact:true}).click()
  const upload=page.getByRole('dialog',{name:'上传图片'})
  await upload.locator('input[type=file]').setInputFiles('../../output/admin-20261114/fixture.png')
  await upload.getByRole('button',{name:'上传并选用'}).click()
  await expect(upload).not.toBeVisible()
  await dialog.getByRole('button',{name:'保存表情草稿'}).click()
  await expect(page.getByRole('row').filter({hasText:label}).getByRole('img')).toBeVisible()
 }
 await add('待机测试')
 await add('开心测试')
 const row=page.getByRole('row').filter({hasText:'待机测试'})
 await row.getByRole('button',{name:'下架',exact:true}).click()
 await expect(row.getByText('已下架')).toBeVisible()
 await row.getByRole('button',{name:'上架',exact:true}).click()
 await expect(row.getByText('已上架')).toBeVisible()
 await row.getByRole('button',{name:'编辑',exact:true}).click()
 dialog=page.getByRole('dialog',{name:'编辑表情'})
 await dialog.locator('.el-form-item').filter({hasText:'表情名称'}).locator('input').fill('平静待机')
 await dialog.getByRole('button',{name:'保存表情草稿'}).click()
 await page.getByPlaceholder('搜索表情名称 / ID').fill('平静')
 const edited=page.getByRole('row').filter({hasText:'平静待机'})
 await expect(edited).toBeVisible()
 await expect(page.getByRole('row').filter({hasText:'开心测试'})).toHaveCount(0)
 const login=await page.request.post(base+'/admin/v1/login',{data:{username:'admin',password:'Brand-fixture-12345'}})
 const headers={Authorization:'Bearer '+(await login.json()).token}
 async function read(){
  const response=await page.request.get(base+'/admin/v1/bird/brand-ips',{headers})
  return (await response.json()).items.find(x=>x.name===name)
 }
 const before=await read()
 expect(before.mainAssetId).toBe(before.expressions[0].assetId)
 expect(before.mainAssetId).not.toBe(before.expressions[1].assetId)
 await edited.getByRole('button',{name:'下架',exact:true}).click()
 await expect(edited.getByText('已下架')).toBeVisible()
 await page.getByRole('button',{name:'发布更新',exact:true}).click()
 await expect(page.getByText('请上传并上架「正常」表情图。',{exact:true})).toBeVisible()
 await edited.getByRole('button',{name:'上架',exact:true}).click()
 await expect(edited.getByText('已上架')).toBeVisible()
 await page.getByPlaceholder('搜索表情名称 / ID').fill('')
 const happy=page.getByRole('row').filter({hasText:'开心测试'})
 await happy.getByRole('button',{name:'下架',exact:true}).click()
 await expect(happy.getByText('已下架')).toBeVisible()
 await page.getByRole('button',{name:'发布更新',exact:true}).click()
 await expect(page.getByText('当前 IP 内容已发布，上下架状态保持不变')).toBeVisible()
 const publicConfig=await (await page.request.get(base+'/bird/v1/content')).json()
 const role=publicConfig.content.characters.find(role=>role.id===before.id)
 const appearance=publicConfig.content.appearances.find(look=>look.id===role.defaultAppearanceId)
 expect(appearance.slots.normal).toBe(before.expressions[0].assetId)
 expect(appearance.slots.happy).toBe(before.expressions[0].assetId)
 expect(publicConfig.assets.some(asset=>asset.id===before.expressions[1].assetId)).toBe(false)
 await edited.getByRole('button',{name:'删除',exact:true}).click()
 await page.getByRole('dialog',{name:'删除表情'}).getByRole('button',{name:'确定',exact:true}).click()
 await expect(edited).toHaveCount(0)
 const after=await read()
 expect(after.mainAssetId).toBe(before.expressions[1].assetId)
 await page.getByPlaceholder('搜索表情名称 / ID').fill('')
 await page.screenshot({path:'../../output/brand-expressions-local/expressions.png',fullPage:true})
 await page.getByRole('button',{name:'返回 IP 列表'}).click()
 await expect(ip.getByRole('img')).toBeVisible()
 await page.screenshot({path:'../../output/brand-expressions-local/ip-list.png',fullPage:true})
 expect(errors).toEqual([])
 console.log('Browser checks passed: upload, thumbnails, add, edit, search, delist, relist, delete, main image update.')
 } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
